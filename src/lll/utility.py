"""Utility edition: upload, map, classify, sample, export.

This is a prioritization and statistical estimation aid. Reclassifying an unknown
line as non-lead must follow methods the Illinois EPA accepts. Uploads stay in
memory; nothing is written to disk.
"""

from __future__ import annotations

import os
from io import BytesIO, StringIO

import numpy as np
import pandas as pd

from lll.features import line_status
from lll.ingest import IEPA_TEMPLATE_COLUMNS
from lll.predict import TREAT_AS_LEAD_MESSAGE, confidence_tier
from lll.schema import MATERIALS
from lll.sources import year_band

MIN_KNOWN_FOR_FRESH_MODEL = 200
SAMPLE_SIZE = 60  # fixed size; margin-of-error sizing is deferred
TO_IEPA = {"Lead": "L", "GRR": "GRR", "Non-Lead": "NL", "Unknown": "U"}
LOCAL_FEATURES = ("year_built", "diameter_in", "install_year", "utility_side_material")
UTIL_CATS = list(MATERIALS)

EXPORT_HEADER = (
    "Generated by Lead Line Lens (utility edition prototype). Predictions support "
    "prioritization and statistical estimation only. Reclassifying an unknown line "
    "requires a verification method accepted by the Illinois EPA."
)

TRANSFER_WARNING = (
    "Fewer than 200 known customer-side rows, so scores use the Chicago model. "
    "They help you decide what to check first. They are not a verification."
)


def utility_edition_enabled() -> bool:
    return os.environ.get("LLL_UTILITY_EDITION", "1").strip().lower() in {
        "1", "true", "yes", "on",
    }


def known_customer(df: pd.DataFrame) -> pd.Series:
    return df["customer_side_material"].astype(str).isin(("Lead", "GRR", "Non-Lead"))


def _local_matrix(df: pd.DataFrame) -> pd.DataFrame:
    M = pd.DataFrame(index=df.index)
    for col in ("year_built", "diameter_in", "install_year"):
        if col in df.columns:
            M[col] = pd.to_numeric(df[col], errors="coerce")
        else:
            M[col] = np.nan
    util = (df["utility_side_material"].astype("string")
            if "utility_side_material" in df.columns
            else pd.Series("Unknown", index=df.index))
    M["utility_side_material"] = pd.Categorical(util.fillna("Unknown"), categories=UTIL_CATS)
    return M


def _fit_local(df: pd.DataFrame, seed: int = 0) -> dict:
    """In-memory LightGBM on known customer-side rows. Never written to disk."""
    from sklearn.isotonic import IsotonicRegression

    from lll.train import _lgbm

    known = df.loc[known_customer(df)]
    y = known["customer_side_material"].isin(("Lead", "GRR")).astype(int)
    X = _local_matrix(known)
    model = _lgbm(len(X), seed)
    model.fit(X, y)
    raw = model.predict_proba(X)[:, 1]
    cal = IsotonicRegression(out_of_bounds="clip", y_min=0.0, y_max=1.0)
    cal.fit(raw, y.to_numpy())
    return {"model": model, "calibrator": cal, "local": True, "version": "utility-local"}


def _score(df: pd.DataFrame, bundle: dict) -> pd.Series:
    if bundle.get("local"):
        raw = bundle["model"].predict_proba(_local_matrix(df))[:, 1]
        p = bundle["calibrator"].predict(raw)
        return pd.Series(np.clip(p, 0.0, 1.0), index=df.index)
    from lll.predict import predict_frame

    return predict_frame(df, bundle)


def classify(df: pd.DataFrame, model: dict | None = None) -> tuple[pd.DataFrame, str | None]:
    """Train fresh on >= MIN_KNOWN_FOR_FRESH_MODEL known rows, else the Chicago model.

    Recorded materials are never overwritten. Returns (frame, transfer_warning or None).
    """
    out = df.copy()
    n_known = int(known_customer(out).sum())
    warning = None
    y = None
    if n_known >= MIN_KNOWN_FOR_FRESH_MODEL:
        y = out.loc[known_customer(out), "customer_side_material"].isin(("Lead", "GRR"))
    if n_known >= MIN_KNOWN_FOR_FRESH_MODEL and y is not None and int(y.nunique()) >= 2:
        bundle = _fit_local(out)
        source = "fresh"
    else:
        bundle = model
        if bundle is None:
            from lll.predict import load_model

            bundle = load_model()
        warning = TRANSFER_WARNING
        if n_known >= MIN_KNOWN_FOR_FRESH_MODEL:
            warning = (
                "Known rows are all one class, so scores use the Chicago model. "
                "They are not a verification."
            )
        source = "chicago_transfer"
    p = _score(out, bundle)
    out["probability_lead"] = p
    out["pred_tier"] = [confidence_tier(float(v)) for v in p]
    out["model_source"] = source
    out["message"] = TREAT_AS_LEAD_MESSAGE
    return out, warning


def stratified_sample_plan(
    df: pd.DataFrame, n: int = SAMPLE_SIZE, seed: int = 0
) -> pd.DataFrame:
    """Fixed-size stratified sample of unknown customer-side lines (not MOE-sized)."""
    unk = df.loc[df["customer_side_material"].astype(str).eq("Unknown")].copy()
    if unk.empty:
        return unk.iloc[0:0]
    n = min(int(n), len(unk))
    year = (pd.to_numeric(unk["year_built"], errors="coerce")
            if "year_built" in unk.columns
            else pd.Series(np.nan, index=unk.index))
    band = year_band(year).astype("string").fillna("unknown year")
    util = (unk["utility_side_material"].astype("string")
            if "utility_side_material" in unk.columns
            else pd.Series("Unknown", index=unk.index))
    unk["_stratum"] = band + " | " + util
    parts = []
    for _, g in unk.groupby("_stratum", dropna=False):
        k = max(1, int(round(len(g) * n / len(unk))))
        k = min(k, len(g))
        parts.append(g.sample(n=k, random_state=seed))
    out = pd.concat(parts)
    if len(out) > n:
        out = out.sample(n=n, random_state=seed)
    elif len(out) < n:
        rest = unk.drop(index=out.index, errors="ignore")
        extra = min(n - len(out), len(rest))
        if extra:
            out = pd.concat([out, rest.sample(n=extra, random_state=seed)])
    cols = [c for c in (
        "line_id", "address", "utility_side_material", "year_built", "diameter_in",
        "probability_lead", "pred_tier", "_stratum",
    ) if c in out.columns]
    return (out[cols].rename(columns={"_stratum": "stratum"})
            .sort_values("stratum").reset_index(drop=True))


def _cell_date(v) -> str:
    if v is None or (isinstance(v, float) and np.isnan(v)) or pd.isna(v):
        return ""
    ts = pd.to_datetime(v, errors="coerce")
    if pd.isna(ts):
        return ""
    return ts.strftime("%Y-%m-%d")


def export_il_epa_template(df: pd.DataFrame) -> bytes:
    """CSV in the Illinois EPA inventory template, with EXPORT_HEADER.

    Official material columns stay as recorded. Predictions are extra columns.
    """
    n = len(df)
    table = pd.DataFrame({c: [""] * n for c in IEPA_TEMPLATE_COLUMNS}, index=df.index)
    util = (df["utility_side_material"].astype(str) if "utility_side_material" in df.columns
            else pd.Series(["Unknown"] * n, index=df.index))
    cust = (df["customer_side_material"].astype(str) if "customer_side_material" in df.columns
            else pd.Series(["Unknown"] * n, index=df.index))
    whole = line_status(util, cust)
    if "address" in df.columns:
        table["service_address"] = df["address"].astype("string").fillna("")
    if "line_id" in df.columns:
        table["lcr_site_id"] = df["line_id"].astype("string")
    table["pws_material"] = util.map(TO_IEPA).fillna("U")
    table["customer_material"] = cust.map(TO_IEPA).fillna("U")
    table["overall_class"] = whole.map(TO_IEPA).fillna("U")
    if "install_year" in df.columns:
        table["customer_install_year"] = pd.to_numeric(df["install_year"], errors="coerce")
    if "utility_install_year" in df.columns:
        table["pws_install_year"] = pd.to_numeric(df["utility_install_year"], errors="coerce")
    if "verification_method" in df.columns:
        table["source"] = df["verification_method"].astype("string").fillna("")
    if "replacement_date" in df.columns:
        table["replaced_date"] = df["replacement_date"].map(_cell_date)
    if "notification_date" in df.columns:
        table["notified_date"] = df["notification_date"].map(_cell_date)
    if "probability_lead" in df.columns:
        table["predicted_lead_prob"] = pd.to_numeric(df["probability_lead"], errors="coerce")
        if "pred_tier" in df.columns:
            table["predicted_tier"] = df["pred_tier"]
        if "model_source" in df.columns:
            table["model_source"] = df["model_source"]
    buf = StringIO()
    buf.write("# " + EXPORT_HEADER + "\n")
    table.to_csv(buf, index=False)
    return buf.getvalue().encode("utf-8")


def methods_memo(run: dict) -> str:
    """Two-page methods memo rendered from templates/methods_memo.j2."""
    from jinja2 import Environment, FileSystemLoader

    from lll import TEMPLATE_DIR

    env = Environment(loader=FileSystemLoader(str(TEMPLATE_DIR)),
                      autoescape=False, keep_trailing_newline=True)
    text = env.get_template("methods_memo.j2").render(**run)
    return "\n".join(line.rstrip() for line in text.splitlines()).strip() + "\n"


def summarize(df: pd.DataFrame) -> dict:
    """JSON-safe counts for the API and the Streamlit page."""
    cust = df["customer_side_material"].astype(str)
    n = int(len(df))
    n_known = int(known_customer(df).sum())
    n_unknown = int(cust.eq("Unknown").sum())
    p = None
    if "probability_lead" in df.columns:
        p = pd.to_numeric(df["probability_lead"], errors="coerce")
    mean_unk = None
    if p is not None and n_unknown:
        mean_unk = float(p.loc[cust.eq("Unknown")].mean())
    return {
        "n_rows": n,
        "n_known": n_known,
        "n_unknown": n_unknown,
        "n_lead": int(cust.eq("Lead").sum()),
        "n_grr": int(cust.eq("GRR").sum()),
        "n_nonlead": int(cust.eq("Non-Lead").sum()),
        "mean_p_unknown": mean_unk,
        "model_source": (None if "model_source" not in df or df.empty
                         else str(df["model_source"].iloc[0])),
    }


def to_xlsx_bytes(df: pd.DataFrame) -> bytes:
    """Canonical inventory as xlsx bytes (for tests that round-trip an upload)."""
    buf = BytesIO()
    df.to_excel(buf, index=False)
    return buf.getvalue()
